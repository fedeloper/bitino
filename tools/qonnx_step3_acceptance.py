#!/usr/bin/env python3
"""Step-3 acceptance of the QONNX route (docs/qonnx-frontend.md § Plan, step 3; report docs/qonnx-step3.md): every
transformer network (BiBERT, Bi-ViT, GSB, BHViT) and every network with an image-feature front end (the 18 "Faster
Than Lies" detectors: ImageGrayU8, FftLogMagnitude, LocalBinaryPattern) of the registry, written to a canonical QONNX
file of the Bitino profile by the group writer (tools/export_groups_qonnx.py, python/bitino/qonnx_groups.py),
checked with check-qonnx, imported (tools/import_qonnx.py, which dispatches on the file's bitino.import) and compared
with the published files.

Runs in .cache/venv-qonnx with python -I; the exports run in the families' reference environments (read only,
python -I) and .cache/venv-qonnx (stage 2):

  scripts/capped.sh 8G nice -n 10 env OMP_NUM_THREADS=2 .cache/venv-qonnx/bin/python -I tools/qonnx_step3_acceptance.py \
      [--only ID ...] [--file model.bitino|model_sign_zero.bitino] [--skip-run] [--no-verify] [--no-export] \
      [--keep-files] [--cache-dir DIR] [--artifacts-dir DIR] [--bench build/host/bitino_bench] [--out summary.json]

Scope (networks()): every recipe of registry/recipes.json whose converter is tools/convert_bibert.py,
tools/convert_bivit.py (Bi-ViT and GSB), tools/convert_bhvit.py or tools/convert_ftl_deepfake.py, and every published
float file of each (model.bitino, model_sign_zero.bitino where published). The int8_full files are step 5.

Per file, into <cache>/qonnx_step3/<id>/<model|model_sign_zero>/ (never artifacts/):
  1. tools/export_groups_qonnx.py: checkpoint SHA-256 check, the deployed graph rebuilt from the checkpoint with the
     legacy adapter + passes (+ the recipe's derive step) and compared with the published hashes, the canonical
     model.onnx (refused unless check-qonnx passes), export.json;
  2. tools/check_qonnx.py on model.onnx (findings by level);
  3. tools/import_qonnx.py --naming exporter --cleanup none: import (group mapping), Level-3 verification (float32
     reference onnxruntime cross-checked with qonnx execute_onnx, OnnxF64 fp64, first binarization flip) on the first
     output, C++ host runtime stages reference / optimized;
  4. comparison with artifacts/<id>/<file>: data SHA-256, graph SHA-256 and, for model.bitino, the recipe's
     expected hashes. The identity bar (user decision 2026-11-20, docs/qonnx-profile.md Q11): data + graph SHA-256
     identity (tensor data and graph structure including every layer / node / constant name, byte for byte); the
     manifest is NOT compared. Outputs of both files on the check set: C++ runtime stages reference and optimized,
     bit for bit (every sample), the numpy executor on the first output (the published file on the first 16
     samples, NUMPY_SAMPLES), and the C++ reference stage of the re-imported file bit for bit against its numpy
     executor (every sample).
Level 3 as steps 1 and 2 (FLIP_REL, NOFLIP_REL). Unless --keep-files, model.onnx and the re-imported model.bitino
are deleted after their row is evaluated (disk; both are regenerated by steps 1 and 3, their SHA-256 are in the
summary). Writes reports/qonnx_step3/summary.json (merged with earlier runs).
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(ROOT, "python"))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import export_groups_qonnx as egq  # noqa: E402
from bitino import executor, format as bfformat, qonnx_groups as qg  # noqa: E402
from bitino.fetch import data_sha256, graph_sha256, sha256_file  # noqa: E402

FLIP_REL = 1e-3
NUMPY_SAMPLES = 16      # published file in the numpy executor: the first 16 samples (C++ stages: every sample)
NOFLIP_REL = 1e-5


def bits_equal(a: np.ndarray, b: np.ndarray) -> bool:
    return a.shape == b.shape and bool(np.array_equal(np.ascontiguousarray(a).view(np.uint32), np.ascontiguousarray(b).view(np.uint32)))


def export_check(d: str, mid: str, artifacts: str, eval_dir: str) -> dict:
    """Source framework vs the canonical file (fp32: onnxruntime reference; fp64: OnnxF64) on the samples of the
    published conversion's reference files: every sample, or the subset its conversion report lists
    (sample_indices: the FTL COCOFake / DFFD conversions used 64 evenly spaced samples); a single-logit source is
    compared as [0, logit], the IR head's form."""
    from bitino.validation.metrics import compare_outputs
    em = json.load(open(os.path.join(eval_dir, "manifest.json")))
    labels_all = np.array([s["label"] for s in em["samples"]])
    rep = json.load(open(os.path.join(artifacts, mid, "conversion_report.json")))
    sel = rep.get("sample_indices")
    out = {"samples": "all" if sel is None else f"{len(sel)} (sample_indices of the published conversion report)"}
    for src_name, ref_name, dt, tag in (("source_logits.f32", "reference_logits.f32", np.float32, "fp32"),
                                        ("source_logits_f64.f64", "reference_logits_f64.f64", np.float64, "fp64")):
        sp, rp = os.path.join(d, src_name), os.path.join(d, ref_name)
        if not (os.path.exists(sp) and os.path.exists(rp)):
            continue
        r_ = np.fromfile(rp, dt).reshape(len(labels_all), -1)
        idx = np.arange(len(r_)) if sel is None else np.asarray(sel, int)
        s_ = np.fromfile(sp, dt).reshape(len(idx), -1)
        r_ = r_[idx]
        if s_.shape[1] == 1 and r_.shape[1] == 2:
            s_ = np.concatenate([np.zeros_like(s_), s_], axis=1)
        out[tag] = compare_outputs(s_, r_, labels_all[idx])
    return out


def networks() -> list:
    return egq.step3_models()


def ensure_sources(mid: str, cache: str) -> dict:
    """Source trees of the recipe that are not in <cache>/repos are fetched (pinned commit, bitino.fetch.get_source)
    into their own directory <cache>/qonnx_step3/_src (untrusted downloads: nothing runs from there but the
    authors' model code that the legacy converter imports, as in a recorded conversion)."""
    from bitino import fetch
    rec = egq.recipes()[mid]
    out = {}
    for s in rec.get("sources", []):
        p = egq.local_paths(mid, cache)["sources"][s["name"]]
        if not os.path.isdir(p):
            home = os.path.join(cache, "qonnx_step3", "_src")
            os.makedirs(home, exist_ok=True)
            got = fetch.get_source(s, home)
            if os.path.abspath(got.rstrip("/")) != os.path.abspath(p.rstrip("/")):
                raise SystemExit(f"{mid}: source {s['name']} fetched to {got}, expected {p}")
        out[s["name"]] = p
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skip-run", action="store_true", help="only compare (exports / imports already in <cache>/qonnx_step3)")
    ap.add_argument("--only", action="append", help="model id (repeatable)")
    ap.add_argument("--file", choices=("model.bitino", "model_sign_zero.bitino"), help="one published file only")
    ap.add_argument("--no-verify", action="store_true", help="identity only: import without the eval set (no Level-3 run)")
    ap.add_argument("--no-export", action="store_true", help="re-import the existing model.onnx (no torch run)")
    ap.add_argument("--keep-files", action="store_true", help="keep model.onnx and the re-imported model.bitino")
    ap.add_argument("--cache-dir", default=os.path.join(ROOT, ".cache"))
    ap.add_argument("--artifacts-dir", default=os.path.join(ROOT, "artifacts"), help="published conversions (read only)")
    ap.add_argument("--bench", default=os.path.join(ROOT, "build", "host", "bitino_bench"))
    ap.add_argument("--out", default=os.path.join(ROOT, "reports", "qonnx_step3", "summary.json"))
    args = ap.parse_args()
    cache = os.path.abspath(args.cache_dir)
    venv_q = os.path.join(cache, "venv-qonnx", "bin", "python")
    recipes = egq.recipes()
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    old = json.load(open(args.out)) if os.path.exists(args.out) else {"files": {}}
    rows = old.get("files", {})
    env = dict(os.environ, OMP_NUM_THREADS=os.environ.get("OMP_NUM_THREADS", "2"), OPENBLAS_NUM_THREADS=os.environ.get("OMP_NUM_THREADS", "2"),
               MKL_NUM_THREADS=os.environ.get("OMP_NUM_THREADS", "2"))
    failed = []
    for mid in networks():
        if args.only and mid not in args.only:
            continue
        rec = recipes[mid]
        fam = egq.family_of(mid)
        ev = rec["eval"]
        eval_dir = os.path.join(cache, "data", ev["dir"])
        for pub_name in egq.published_files(mid, args.artifacts_dir):
            if args.file and pub_name != args.file:
                continue
            variant = pub_name[: -len(".bitino")]
            key = f"{mid}/{variant}"
            d = os.path.join(cache, "qonnx_step3", mid, variant)
            os.makedirs(d, exist_ok=True)
            row = {"model_id": mid, "published_file": pub_name, "family": fam, "legacy_converter": rec["converter"],
                   "eval_dir": ev["dir"], "preprocess": ev["preprocess"]}
            t0 = time.time()
            onnx_path = os.path.join(d, "model.onnx")
            if not args.skip_run and not args.no_export:
                ensure_sources(mid, cache)
                py = os.path.expanduser(egq.ENVS[fam])
                r = subprocess.run([py, "-I", os.path.join(ROOT, "tools", "export_groups_qonnx.py"), "--model-id", mid, "--file", pub_name,
                                    "--out-dir", d, "--cache-dir", cache, "--artifacts-dir", args.artifacts_dir, "--qonnx-python", venv_q],
                                   env=env)
                if r.returncode:
                    exp = json.load(open(os.path.join(d, "export.json"))) if os.path.exists(os.path.join(d, "export.json")) else {}
                    row.update({"status": "FAIL", "reason": f"export failed (rc {r.returncode}): {exp.get('error', '')}",
                                "rebuilt_vs_published": exp.get("rebuilt_vs_published")})
                    rows[key] = row
                    failed.append(key)
                    json.dump({"schema": "bitino.qonnx_step3.v1", "files": rows}, open(args.out, "w"), indent=1)
                    continue
            exp = json.load(open(os.path.join(d, "export.json")))
            row["export"] = {k: exp.get(k) for k in ("checkpoint_sha256", "bnext_init_checkpoint_sha256", "exporter", "onnx_sha256",
                                                     "onnx_bytes", "import_args", "writer", "ir_nodes", "ir_constants", "torch",
                                                     "torch_threads", "binarize", "derived", "rebuilt_vs_published", "adapter")}
            if os.path.exists(onnx_path):
                chk = subprocess.run([venv_q, "-I", os.path.join(ROOT, "tools", "check_qonnx.py"), onnx_path, "--json", "-"],
                                     capture_output=True, text=True)
                cj = json.loads(chk.stdout)
                cj = cj[0] if isinstance(cj, list) else cj
                row["check_qonnx"] = {"returncode": chk.returncode, "passed": cj.get("passed"),
                                      "warnings": sorted({f["code"] for f in cj.get("findings", []) if f.get("level") == "warning"}),
                                      "errors": sorted({f["code"] for f in cj.get("findings", []) if f.get("level") == "error"}),
                                      "op_counts": (cj.get("summary") or {}).get("op_counts"),
                                      "onnx_nodes": (cj.get("summary") or {}).get("nodes")}
            elif "check_qonnx" in rows.get(key, {}):
                row["check_qonnx"] = rows[key]["check_qonnx"]
            if not args.skip_run:
                cmd = [venv_q, "-I", os.path.join(ROOT, "tools", "import_qonnx.py"), onnx_path, "--model-id", mid, "--out-dir", d,
                       "--exporter", exp["exporter"], "--source-json", os.path.join(d, "export.json"), "--file-name", "model.bitino"] \
                    + list(exp["import_args"])
                if not args.no_verify:
                    cmd += ["--eval-dir", eval_dir, "--preprocess", ev["preprocess"], "--bench", args.bench, "--stages", "reference,optimized"]
                r = subprocess.run(cmd, env=env)
                row["import_returncode"] = r.returncode
            cpath = os.path.join(d, "conversion_report.json")
            if not os.path.exists(cpath) or (not args.skip_run and row.get("import_returncode") not in (0, 1)
                                             and os.path.getmtime(cpath) < t0):
                row.update({"status": "FAIL", "reason": f"import did not finish (rc {row.get('import_returncode')}; "
                                                        "killed by the memory cap or an exception, see the log)"})
                rows[key] = row
                failed.append(key)
                json.dump({"schema": "bitino.qonnx_step3.v1", "files": rows}, open(args.out, "w"), indent=1)
                continue
            crep = json.load(open(cpath))
            if "import_error" in crep:
                row.update({"status": "FAIL", "reason": f"import error: {crep['import_error']}"})
                rows[key] = row
                failed.append(key)
                json.dump({"schema": "bitino.qonnx_step3.v1", "files": rows}, open(args.out, "w"), indent=1)
                continue
            new = os.path.join(d, "model.bitino")
            pub = os.path.join(args.artifacts_dir, mid, pub_name)
            row["published"] = {"data_sha256": data_sha256(pub), "graph_sha256": graph_sha256(pub)}
            e = rec["expected"].get(pub_name)
            row["recipe_expected"] = {"data_sha256": e["data_sha256"], "graph_sha256": e["graph_sha256"]} if e else None
            if os.path.exists(new):
                row["reimported"] = {"data_sha256": data_sha256(new), "graph_sha256": graph_sha256(new), "bytes": os.path.getsize(new)}
            else:
                row["reimported"] = {"data_sha256": crep["data_sha256"], "graph_sha256": crep["graph_sha256"], "bytes": crep["file_bytes"]}
            row["data_identical"] = row["reimported"]["data_sha256"] == row["published"]["data_sha256"]
            row["graph_identical"] = row["reimported"]["graph_sha256"] == row["published"]["graph_sha256"]
            row["recipe_identical"] = (row["reimported"]["data_sha256"] == e["data_sha256"] and
                                       row["reimported"]["graph_sha256"] == e["graph_sha256"]) if e else None
            if not args.no_verify and os.path.exists(new):
                gb = bfformat.read(new)
                ga = bfformat.read(pub)
                pre = json.load(open(os.path.join(eval_dir, "manifest.json")))["preprocessing"][ev["preprocess"]]
                inp = os.path.join(eval_dir, pre["file"])
                X = qg.load_eval_inputs(eval_dir, ev["preprocess"], ga)
                n = len(next(iter(X.values())))
                n_np = min(n, NUMPY_SAMPLES)       # the published file in the numpy executor (the re-imported one: all)
                ya = np.stack([executor.run(ga, {k: v[i:i + 1] for k, v in X.items()})[ga.outputs[0]].reshape(-1) for i in range(n_np)])
                yb = np.fromfile(os.path.join(d, "numpy_logits_fused.f32"), np.float32).reshape(n, -1)
                outs = {}
                for st in ("reference", "optimized"):
                    for tag, path in (("published", pub), ("reimported", new)):
                        o = os.path.join(d, f"cpp_{tag}_{st}.f32")
                        outs[(tag, st)] = qg.run_bench(args.bench, path, inp, o, st)
                        os.remove(o)
                row["outputs_check_set"] = {"n_samples": int(n), "eval_set": ev["dir"], "graph_outputs": list(gb.outputs),
                                            "numpy_f32_bit_identical (first output)": bits_equal(ya.astype(np.float32), yb[:n_np]),
                                            "numpy_f32_samples_published": int(n_np),
                                            "cpp_reference_bit_identical": bits_equal(outs[("published", "reference")], outs[("reimported", "reference")]),
                                            "cpp_optimized_bit_identical": bits_equal(outs[("published", "optimized")], outs[("reimported", "optimized")]),
                                            "cpp_reference_vs_numpy_reimported_bit_identical": bits_equal(outs[("reimported", "reference")], yb.reshape(-1))}
                del ga, gb, X
                v = crep.get("verification", {})
                sem = v.get("semantic_check_ir_f64_vs_reference_f64", {})
                ec32 = v.get("source_framework_f32_vs_qonnx_f32 (export check)", {})
                ec64 = v.get("source_framework_f64_vs_qonnx_f64 (export check)", {})
                fl = v.get("binarization_flips_vs_source", {})
                ref64 = np.fromfile(os.path.join(d, "reference_logits_f64.f64"), np.float64).reshape(n, -1)
                ir64 = np.fromfile(os.path.join(d, "numpy_logits_f64.f64"), np.float64).reshape(n, -1)
                per = np.abs(ir64 - ref64).max(axis=1)
                scale = np.abs(ref64).max(axis=1)
                fls = fl.get("samples", [])
                complete = len(fls) == fl.get("n_samples_with_flips", 0)
                f64 = {q["sample"]: q["ir_f64_vs_source_f64"] for q in fls if "ir_f64_vs_source_f64" in q}
                dev = [int(i) for i in np.where(per > 1e-6)[0]]
                flip_rel = {i: f64[i]["max_abs_pre_source"] / max(f64[i]["typical_abs_pre_source"], 1e-30) for i in dev if i in f64}
                noflip_rel = {i: float(per[i] / max(scale[i], 1e-30)) for i in dev if i not in f64}
                level3 = {"rule": f"deviation > 1e-6: first flip at |pre| <= {FLIP_REL:g} x median |pre| of its binarizer, "
                                  f"or no flip and max |delta| <= {NOFLIP_REL:g} x max |output|",
                          "samples_le_1e-6": int(np.sum(per <= 1e-6)), "deviating": len(dev),
                          "with_flip": len(flip_rel), "max_rel_pre_at_first_flip": max(flip_rel.values(), default=None),
                          "max_abs_pre_at_first_flip": max((f64[i]["max_abs_pre_source"] for i in flip_rel), default=None),
                          "without_flip": len(noflip_rel), "max_rel_delta_without_flip": max(noflip_rel.values(), default=None),
                          "max_abs_delta_without_flip": max((float(per[i]) for i in noflip_rel), default=None),
                          "flip_list_complete": complete}
                level3["passed"] = bool(complete and all(r_ <= FLIP_REL for r_ in flip_rel.values())
                                        and all(r_ <= NOFLIP_REL for r_ in noflip_rel.values()))
                l4 = v.get("acceptance") or {}
                cpp = crep.get("cpp_host", [])
                row["verification"] = {
                    "acceptance": {"rule": "Level 3 (docs/numerical-correctness.md) + C++ reference stage bit-exact with numpy",
                                   "passed": level3["passed"], "level3": level3,
                                   "level4_informational": {"criterion": l4.get("criterion"), "passed": l4.get("passed")}},
                    "semantic_f64_max_abs": sem.get("max_abs_error"), "semantic_f64_top1": sem.get("top1_agreement"),
                    "binarization_flip_samples": fl.get("n_samples_with_flips"),
                    "reference_f32_vs_qonnx_execute_onnx": v.get("reference_f32_vs_qonnx_execute_onnx"),
                    "qonnx_f32_vs_f64_top1_disagreements": v.get("reference_f32_vs_f64", {}).get("n_top1_disagreements"),
                    "numpy_f32_vs_qonnx_f64": {k: v.get("numpy_f32_vs_reference_f64", {}).get(k) for k in ("top1_agreement", "n_top1_disagreements")},
                    "export_check_source_f32_vs_qonnx_f32": {k: ec32.get(k) for k in ("max_abs_error", "top1_agreement", "n_top1_disagreements", "cosine_min")},
                    "export_check_source_f64_vs_qonnx_f64": {k: ec64.get(k) for k in ("max_abs_error", "top1_agreement", "n_top1_disagreements", "cosine_min")},
                    "cpp_host_reference_exact_vs_numpy": [c.get("exact_vs_numpy") for c in cpp if c.get("stage") == "reference"],
                }
            elif "outputs_check_set" in rows.get(key, {}) and args.skip_run:
                row["outputs_check_set"] = rows[key]["outputs_check_set"]
                row["verification"] = rows[key].get("verification")
            if row.get("verification"):
                ec = export_check(d, mid, args.artifacts_dir, eval_dir)
                keys = ("max_abs_error", "top1_agreement", "n_top1_disagreements", "cosine_min")
                row["verification"]["export_check_samples"] = ec["samples"]
                for tag, name in (("fp32", "export_check_source_f32_vs_qonnx_f32"), ("fp64", "export_check_source_f64_vs_qonnx_f64")):
                    if tag in ec:
                        row["verification"][name] = {k: ec[tag].get(k) for k in keys}
            row["import_rules"] = (crep.get("import") or {}).get("rules")
            row["seconds"] = round(time.time() - t0, 1)
            ident = row["data_identical"] and row["graph_identical"] and (row["recipe_identical"] is not False)
            ok_chk = bool((row.get("check_qonnx") or {}).get("passed")) and not (row.get("check_qonnx") or {}).get("warnings")
            if args.no_verify or "verification" not in row or row.get("verification") is None:
                row["status"] = "IDENTICAL (data + graph SHA-256, names included; manifest not compared), not verified" \
                    if ident and ok_chk else "FAIL"
            else:
                o = row["outputs_check_set"]
                ver = row["verification"]
                acc_ok = bool(ver["acceptance"]["passed"]) and all(ver["cpp_host_reference_exact_vs_numpy"] or [False])
                outs_ok = all(o[k] for k in ("numpy_f32_bit_identical (first output)", "cpp_reference_bit_identical",
                                              "cpp_optimized_bit_identical", "cpp_reference_vs_numpy_reimported_bit_identical"))
                row["status"] = "PASS: data + graph SHA-256 identical (names included; manifest not compared), outputs " \
                                "bit-identical, Level 3 passed" if ident and ok_chk and outs_ok and acc_ok else "FAIL"
            if row["status"] == "FAIL":
                failed.append(key)
            elif not args.keep_files:
                for f in ("model.onnx", "model.bitino"):
                    if os.path.exists(os.path.join(d, f)):
                        os.remove(os.path.join(d, f))
            rows[key] = row
            print(f"{key:56s} check {'ok' if ok_chk else 'FAIL'} data {'=' if row['data_identical'] else '!='} "
                  f"graph {'=' if row['graph_identical'] else '!='} -> {row['status']} ({row['seconds']} s)", flush=True)
            json.dump({"schema": "bitino.qonnx_step3.v1", "files": rows}, open(args.out, "w"), indent=1)
    json.dump({"schema": "bitino.qonnx_step3.v1", "files": rows}, open(args.out, "w"), indent=1)
    if failed:
        print("FAILED:", failed)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
